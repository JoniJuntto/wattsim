#!/usr/bin/env bun
/**
 * Generates the TextMate grammar (dist/wattsim.tmLanguage.json) from the DSL's own sources, so highlighting has
 * no keyword list of its own (DESIGN.md §4: one grammar source):
 * - statement and declaration keywords: the lexer's `KEYWORDS`;
 * - sub-words (`evse`, `within`, chaos faults, ev actions, ...), distributions, units: read from the parser's source,
 *   its `atWord('x')` / `expectWord('x')` calls and its `new Set([...])` word tables;
 * - OCPP action names: `ACTIONS` of every version in `@wattsim/protocol`.
 * The token rules (strings with `{var}` interpolation, durations, numbers with units, comments, JSON payloads) are
 * written here. Run: `bun scripts/grammar.ts` (part of `bun run build`).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { ACTIONS, OCPP_VERSIONS } from '@wattsim/protocol';
import { KEYWORDS } from '@wattsim/scenario';

export const SCOPE = 'source.wattsim';
export const GRAMMAR_PATH = join(import.meta.dir, '../dist/wattsim.tmLanguage.json');

const WORD = /^[A-Za-z_][A-Za-z0-9_]*$/;
const escapeRe = (w: string) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/** Longest first, so `min` wins over `m` in an alternation. */
const alt = (words: Iterable<string>) =>
  [...new Set(words)]
    .sort((a, b) => b.length - a.length || a.localeCompare(b))
    .map(escapeRe)
    .join('|');

export type ParserWords = {
  /** Words the parser matches after a keyword. */
  subwords: string[];
  /** `normal`, `uniform`, `exp`. */
  distributions: string[];
  /** Units that may stand apart from their number (`60 kWh`). */
  propUnits: string[];
  /** Duration units (`ms`, `s`, `min`, ...). */
  durationUnits: string[];
};

/** Read the parser's word tables from its source. Throws when a table is missing, so a parser refactor fails loudly. */
export function parserWords(src: string): ParserWords {
  const sets = new Map<string, string[]>();
  for (const m of src.matchAll(/const (\w+)(?::[^=]+)?= new Set\(\[([^\]]*)\]\)/g)) {
    sets.set(
      m[1] as string,
      [...(m[2] as string).matchAll(/'([^']*)'/g)].map((w) => w[1] as string),
    );
  }
  const durations = /const DURATION_UNITS[^{]*\{([^}]*)\}/.exec(src)?.[1];
  const need = (name: string) => {
    const s = sets.get(name);
    if (!s?.length) throw new Error(`grammar: parser table ${name} not found in packages/scenario/src/parser.ts`);
    return s;
  };
  const distributions = need('DISTRIBUTIONS');
  const propUnits = need('PROP_UNITS');
  if (!durations) throw new Error('grammar: DURATION_UNITS not found in packages/scenario/src/parser.ts');
  const durationUnits = [...durations.matchAll(/^\s*'?(\w+)'?\s*:/gm)].map((m) => m[1] as string);
  const called = [...src.matchAll(/(?:atWord|expectWord)\('([^']+)'/g)].map((m) => m[1] as string);
  const tables = [...sets].filter(([name]) => name !== 'DISTRIBUTIONS' && name !== 'PROP_UNITS').flatMap(([, w]) => w);
  const subwords = [...new Set([...called, ...tables])]
    .filter((w) => WORD.test(w) && !KEYWORDS.has(w) && !durationUnits.includes(w))
    .sort();
  return { subwords, distributions, propUnits, durationUnits };
}

export function parserSource(): string {
  return readFileSync(join(dirname(Bun.resolveSync('@wattsim/scenario', import.meta.dir)), 'parser.ts'), 'utf8');
}

export function buildGrammar(words: ParserWords = parserWords(parserSource())): Record<string, unknown> {
  const keywords = [...KEYWORDS];
  const actions = OCPP_VERSIONS.flatMap((v) => ACTIONS[v]);
  const ident = '[A-Za-z_][A-Za-z0-9_]*';
  const notAfterWord = '(?<![A-Za-z0-9_.])';
  return {
    $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
    name: 'wattsim',
    scopeName: SCOPE,
    fileTypes: ['ws'],
    comment: 'Generated by packages/vscode/scripts/grammar.ts from the scenario lexer and parser. Do not edit.',
    patterns: [
      { include: '#comment' },
      { include: '#key' },
      { include: '#string' },
      { include: '#duration' },
      { include: '#number' },
      { include: '#constant' },
      { include: '#declaration' },
      { include: '#keyword' },
      { include: '#action' },
      { include: '#distribution' },
      { include: '#subword' },
      { include: '#unit' },
      { include: '#enum' },
      { include: '#variable' },
      { include: '#punctuation' },
    ],
    repository: {
      comment: { name: 'comment.line.double-slash.wattsim', match: '//.*$' },
      key: {
        comment: 'An object key in a JSON payload, bare or quoted: `{status: "Accepted"}`.',
        match: `(${ident}|"(?:[^"\\\\]|\\\\.)*")\\s*(?=:)`,
        captures: { 1: { name: 'support.type.property-name.wattsim' } },
      },
      string: {
        name: 'string.quoted.double.wattsim',
        begin: '"',
        end: '"|$',
        beginCaptures: { 0: { name: 'punctuation.definition.string.begin.wattsim' } },
        endCaptures: { 0: { name: 'punctuation.definition.string.end.wattsim' } },
        patterns: [
          { name: 'constant.character.escape.wattsim', match: '\\\\.' },
          {
            name: 'meta.interpolation.wattsim',
            match: `(\\{)(${ident})(\\})`,
            captures: {
              1: { name: 'punctuation.section.interpolation.begin.wattsim' },
              2: { name: 'variable.other.interpolated.wattsim' },
              3: { name: 'punctuation.section.interpolation.end.wattsim' },
            },
          },
        ],
      },
      duration: {
        comment: 'A number and a duration unit, with or without a space: `500ms`, `2 min`, `-2s`.',
        match: `${notAfterWord}([-+]?\\d+(?:\\.\\d+)?)\\s*(${alt(words.durationUnits)})\\b`,
        captures: {
          1: { name: 'constant.numeric.duration.wattsim' },
          2: { name: 'keyword.other.unit.duration.wattsim' },
        },
      },
      number: {
        comment: 'Numbers, versions (`2.0.1`) and numbers with an attached unit (`60kWh`, `20%`).',
        match: `${notAfterWord}(-?\\d+(?:\\.\\d+)*)(%|[A-Za-z]+)?`,
        captures: { 1: { name: 'constant.numeric.wattsim' }, 2: { name: 'keyword.other.unit.wattsim' } },
      },
      constant: { name: 'constant.language.wattsim', match: '\\b(?:true|false|null)\\b' },
      declaration: {
        comment: 'The name after `proc` and `call`.',
        match: `\\b(proc|call)\\s+(${ident})`,
        captures: { 1: { name: 'keyword.control.wattsim' }, 2: { name: 'entity.name.function.wattsim' } },
      },
      keyword: { name: 'keyword.control.wattsim', match: `\\b(?:${alt(keywords)})\\b` },
      action: { name: 'support.class.action.wattsim', match: `\\b(?:${alt(actions)})\\b` },
      distribution: {
        name: 'support.function.distribution.wattsim',
        match: `\\b(?:${alt(words.distributions)})(?=\\s*\\()`,
      },
      subword: { name: 'keyword.other.wattsim', match: `\\b(?:${alt(words.subwords)})\\b` },
      unit: { name: 'keyword.other.unit.wattsim', match: `\\b(?:${alt(words.propUnits)})\\b` },
      enum: { name: 'constant.other.enum.wattsim', match: '\\b[A-Z][A-Za-z0-9_]*\\b' },
      variable: { name: 'variable.other.wattsim', match: `\\b${ident}\\b` },
      punctuation: {
        patterns: [
          { name: 'punctuation.section.braces.wattsim', match: '[{}]' },
          { name: 'punctuation.section.brackets.wattsim', match: '[\\[\\]]' },
          { name: 'punctuation.section.parens.wattsim', match: '[()]' },
          { name: 'keyword.operator.range.wattsim', match: '\\.\\.' },
          { name: 'punctuation.separator.wattsim', match: '[,:;]' },
          { name: 'keyword.operator.wattsim', match: '[-+%=]' },
        ],
      },
    },
  };
}

if (import.meta.main) {
  mkdirSync(dirname(GRAMMAR_PATH), { recursive: true });
  writeFileSync(GRAMMAR_PATH, `${JSON.stringify(buildGrammar(), null, 2)}\n`);
  console.log(`wrote ${GRAMMAR_PATH}`);
}
