/** Seeded randomness: FNV-1a to hash a key, mulberry32 to draw from it. Deterministic across runtimes. */

export function hashString(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** A generator of uniform numbers in [0, 1). */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** One uniform number in [0, 1) for a (seed, key) pair, independent of draw order. */
export function uniformFor(seed: number, key: string): number {
  return mulberry32(hashString(`${seed}:${key}`))();
}
